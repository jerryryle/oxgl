// Writes src/generated/webgl-constants.ts: the constants of the WebGL 1 and
// WebGL 2 IDL (WebGL 1.0 §5.14, WebGL 2.0 §3.7), read from KhronosGroup/WebGL
// at the commit conformance/suite.json pins, so the tables match the
// conformance pages that check them. Run it when that pin moves.
import { readFileSync, writeFileSync } from 'node:fs';

const OUTPUT = 'src/generated/webgl-constants.ts';
const { repository, commit } = JSON.parse(readFileSync('conformance/suite.json', 'utf8'));
const RAW = `${repository.replace('https://github.com/', 'https://raw.githubusercontent.com/').replace(/\.git$/, '')}/${commit}`;
const WEBGL1_IDL = 'specs/latest/1.0/webgl.idl';
const WEBGL2_IDL = 'specs/latest/2.0/webgl2.idl';

async function fetchText(path) {
  const response = await fetch(`${RAW}/${path}`);
  if (!response.ok) throw new Error(`fetching ${path} at ${commit}: HTTP ${String(response.status)}`);
  return response.text();
}

/** The `const` members of `interface mixin <name>`, in IDL order. */
function mixinConstants(idl, path, name) {
  const start = idl.indexOf(`interface mixin ${name}`);
  if (start === -1) throw new Error(`${path}: no interface mixin ${name}`);
  const end = idl.indexOf('\n};', start);
  if (end === -1) throw new Error(`${path}: interface mixin ${name} has no closing '};'`);
  const constants = [];
  for (const line of idl.slice(start, end).split('\n')) {
    if (!/^\s*const\b/.test(line)) continue;
    const match = /^\s*const\s+\w+\s+([A-Z]\w*)\s*=\s*(-?(?:0x[0-9A-Fa-f]+|\d+))\s*;\s*(?:\/\/.*|\/\*.*\*\/)?\s*$/.exec(line);
    if (!match) throw new Error(`${path}: cannot parse constant: ${line.trim()}`);
    constants.push([match[1], match[2]]);
  }
  return constants;
}

/** The `//` comment block of an IDL file that starts with its copyright line: the copyright and permission notice. */
function licence(idl, path) {
  const lines = idl.split('\n');
  const start = lines.findIndex((line) => line.startsWith('// Copyright'));
  if (start === -1) throw new Error(`${path}: no copyright notice`);
  const end = lines.findIndex((line, index) => index > start && !line.startsWith('//'));
  return lines.slice(start, end).join('\n');
}

function table(name, constants) {
  const width = Math.max(...constants.map(([key]) => key.length));
  const entries = constants.map(([key, value]) => `  ${`${key}:`.padEnd(width + 1)} ${value},`);
  return `export const ${name} = {\n${entries.join('\n')}\n} as const;\n`;
}

const [webgl1, webgl2] = await Promise.all([fetchText(WEBGL1_IDL), fetchText(WEBGL2_IDL)]);
const v1 = mixinConstants(webgl1, WEBGL1_IDL, 'WebGLRenderingContextBase');
const v2 = mixinConstants(webgl2, WEBGL2_IDL, 'WebGL2RenderingContextBase');
const seen = new Set();
for (const [key] of [...v1, ...v2]) {
  if (seen.has(key)) throw new Error(`constant ${key} is declared twice`);
  seen.add(key);
}
const notices = [...new Set([licence(webgl1, WEBGL1_IDL), licence(webgl2, WEBGL2_IDL)])];

const source = `// Generated by scripts/webgl-constants.mjs from ${repository} at ${commit}:
// ${WEBGL1_IDL} (WebGLRenderingContextBase) and ${WEBGL2_IDL}
// (WebGL2RenderingContextBase). Do not edit. The names and values are taken
// from those files, whose notice follows.
//
${notices.join('\n//\n')}

${table('WEBGL1_CONSTANTS', v1)}
${table('WEBGL2_ONLY_CONSTANTS', v2)}
export const WEBGL2_CONSTANTS = { ...WEBGL1_CONSTANTS, ...WEBGL2_ONLY_CONSTANTS } as const;
`;
writeFileSync(OUTPUT, source);
console.log(`${OUTPUT}: ${String(v1.length)} WebGL 1 and ${String(v2.length)} WebGL 2-only constants`);
